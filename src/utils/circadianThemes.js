/**
 * Returns default circadian mode based on Earth local clock hour:
 * Day: 06:00-17:30, Sunset: 17:30-20:00, Night: 20:00-06:00
 */
export function getCircadianModeFromDate(date = new Date()) {
  const totalMinutes = date.getHours() * 60 + date.getMinutes();
  if (totalMinutes >= 360 && totalMinutes < 1050) return 'day';
  if (totalMinutes >= 1050 && totalMinutes < 1200) return 'sunset';
  return 'night';
}
